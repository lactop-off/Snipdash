const dicts: Record<Locale, Dict> = { ja, en };

export function translator(locale: Locale) {
  const dict = dicts[locale] ?? ja;
  return (key: string): string => dict[key] ?? key;
}

export type T = ReturnType<typeof translator>;

/** Human label for a reminder lead time in minutes (e.g. "15分前" / "1時間前").
 * `0` means "at the due time". */
export function remindLabel(minutes: number, t: T): string {
  if (minutes <= 0) return t("todo.remind.onTime");
  if (minutes < 60) return t("todo.remind.minutes").replace("{n}", String(minutes));
  if (minutes < 1440) {
    const h = minutes / 60;
    return t("todo.remind.hours").replace("{n}", Number.isInteger(h) ? String(h) : h.toFixed(1));
  }
  const d = minutes / 1440;
  return t("todo.remind.days").replace("{n}", Number.isInteger(d) ? String(d) : d.toFixed(1));
}
